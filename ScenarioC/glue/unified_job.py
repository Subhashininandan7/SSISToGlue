"""Independent REFerence PySpark implementation for controlled AWS Glue demo.
NOT generated by AWS SCT. Never present it as a converted SSIS artifact.
"""
import sys
from pyspark.sql import SparkSession, functions as F
from pyspark.sql.types import DecimalType


def options(argv):
    # Explicit, predictable contract rather than exposing arbitrary local filenames.
    keys = ('SCENARIO', 'INPUT_PREFIX', 'OUTPUT_PREFIX', 'AS_OF')
    args={}
    for key in keys:
        needle='--'+key
        if needle not in argv: raise ValueError('Missing argument '+needle)
        idx=argv.index(needle)
        if idx+1>=len(argv):raise ValueError('Missing value for '+needle)
        args[key]=argv[idx+1]
    if args['SCENARIO'] not in ('A','B','C'): raise ValueError('Unknown scenario')
    if not args['INPUT_PREFIX'].startswith('s3://') or not args['OUTPUT_PREFIX'].startswith('s3://'):
        raise ValueError('S3 input and output prefixes are required')
    return args

def main():
    cfg=options(sys.argv)
    spark=SparkSession.builder.appName('SSISGlueDemoReference').getOrCreate()
    src=cfg['INPUT_PREFIX'].rstrip('/')
    dst=cfg['OUTPUT_PREFIX'].rstrip('/')
    dec=DecimalType(18,2)
    def load(name):
        return spark.read.option('header','true').option('mode','FAILFAST').csv(src+'/'+name)
    def save(df,name):
        df.coalesce(1).write.mode('overwrite').option('header','true').csv(dst+'/'+name)
    if cfg['SCENARIO']=='A':
        em=load('Employees.csv')
        if em.groupBy('EmployeeID').count().where('count > 1').limit(1).count():raise ValueError('Duplicate EmployeeID')
        result=(em.where(F.lower(F.trim('Status'))=='active')
            .withColumn('Salary', F.col('Salary').cast(dec))
            .withColumn('Bonus', (F.col('Salary')*F.lit('0.10')).cast(dec))
            .select('EmployeeID','EmployeeName','Department','Salary','Bonus'))
        if result.where('Salary is null').limit(1).count():raise ValueError('Invalid Salary')
        save(result,'ActiveEmployees.csv')
        print('DEMO_METRIC_A: outputRows='+str(result.count()))
    elif cfg['SCENARIO']=='B':
        c=load('Customers.csv');o=load('Orders.csv')
        if c.groupBy('CustomerID').count().where('count > 1').limit(1).count():raise ValueError('Duplicate customer dimension keys')
        if o.groupBy('OrderID').count().where('count > 1').limit(1).count():raise ValueError('Duplicate order IDs')
        # A distinct hit flag ensures the no-match route is based on the lookup side.
        customer=c.select(F.col('CustomerID').alias('_LookupCustomerID'),F.col('CustomerName'))
        joined=o.join(customer,o.CustomerID==customer._LookupCustomerID,'left')
        matched=joined.where(F.col('_LookupCustomerID').isNotNull())
        missing=joined.where(F.col('_LookupCustomerID').isNull())
        valid=(matched.withColumn('Quantity',F.col('Quantity').cast('int'))
             .withColumn('UnitPrice',F.col('UnitPrice').cast(dec))
             .withColumn('Total',(F.col('Quantity')*F.col('UnitPrice')).cast(dec))
             .select('OrderID','CustomerID','CustomerName','Quantity','UnitPrice','Total'))
        if valid.where('Quantity is null or UnitPrice is null').limit(1).count():raise ValueError('Invalid numeric order values')
        rejected=missing.withColumn('Reason',F.lit('CUSTOMER_NOT_FOUND')).select('OrderID','CustomerID','Reason')
        save(valid,'ValidOrders.csv');save(rejected,'RejectedOrders.csv')
        print('DEMO_METRIC_B: valid='+str(valid.count())+' rejected='+str(rejected.count()))
    else:
        d=load('DimCustomer.csv');ch=load('CustomerChanges.csv');day=cfg['AS_OF']
        # Exclusive upper bound: [EffectiveFrom, EffectiveTo). This is intentional.
        if ch.groupBy('CustomerID').count().where('count > 1').limit(1).count():raise ValueError('Duplicate change business keys')
        curr=d.where(F.col('IsCurrent')=='1')
        if curr.groupBy('CustomerID').count().where('count > 1').limit(1).count():raise ValueError('Duplicate current history rows')
        names=['CustomerID','CustomerName','City','EffectiveFrom','EffectiveTo','IsCurrent']
        joined=(ch.alias('n').join(curr.alias('c'),F.col('n.CustomerID')==F.col('c.CustomerID'),'left')
          .select(F.col('n.CustomerID').alias('Id'),F.col('n.CustomerName').alias('NewName'),
                  F.col('n.City').alias('NewCity'),F.col('c.CustomerName').alias('OldName'),
                  F.col('c.City').alias('OldCity'),F.col('c.EffectiveFrom').alias('OldFrom')))
        changes=joined.where(F.col('OldName').isNull() | ~F.col('NewName').eqNullSafe(F.col('OldName')) | ~F.col('NewCity').eqNullSafe(F.col('OldCity')))
        if changes.where(F.col('OldFrom').isNotNull() & (F.col('OldFrom')>=F.lit(day))).limit(1).count():
            raise ValueError('SCD2 change date cannot precede existing effective date')
        change_keys=changes.select('Id').distinct()
        untouched=d.alias('d').join(change_keys.alias('x'),F.col('d.CustomerID')==F.col('x.Id'),'left_anti')
        # Retain all historical rows for changed keys, expire only the current row.
        changed_existing=d.alias('d').join(change_keys.alias('x'),F.col('d.CustomerID')==F.col('x.Id'),'inner').select('d.*')
        expired=changed_existing.withColumn('EffectiveTo', F.when(F.col('IsCurrent')=='1',F.lit(day)).otherwise(F.col('EffectiveTo'))).withColumn('IsCurrent',F.when(F.col('IsCurrent')=='1',F.lit('0')).otherwise(F.col('IsCurrent')))
        incoming=changes.select(F.col('Id').alias('CustomerID'),F.col('NewName').alias('CustomerName'),
                F.col('NewCity').alias('City'),F.lit(day).alias('EffectiveFrom'),
                F.lit('9999-12-31').alias('EffectiveTo'),F.lit('1').alias('IsCurrent'))
        result=untouched.select(names).unionByName(expired.select(names)).unionByName(incoming.select(names))
        if result.where(F.col('IsCurrent')=='1').groupBy('CustomerID').count().where('count > 1').limit(1).count():
            raise ValueError('SCD2 invalid duplicate current versions')
        save(result.select(names),'DimCustomerHistory.csv')
        print('DEMO_METRIC_C: historyRows='+str(result.count())+' newVersions='+str(incoming.count()))
    spark.stop()

if __name__=='__main__':main()
